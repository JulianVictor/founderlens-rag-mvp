"""Typed parsing and structural validation of the corpus manifest (``data/manifest.json``).

The manifest is the single source of truth for which documents form the corpus
and what their exact bytes are. It is authored once at acquisition time and is
never regenerated by validation code.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit

MANIFEST_SCHEMA_VERSION = 1
EXPECTED_CORPUS_ID = "founderlens-financial-research"
EXPECTED_DOCUMENT_COUNT = 4

# Hosts that may serve corpus bytes. Anything else is rejected at parse time
# and again (including redirects) at download time.
ALLOWED_DOWNLOAD_HOSTS: frozenset[str] = frozenset(
    {
        "nvidianews.nvidia.com",  # NVIDIA Newsroom (official press-release PDFs)
        "s206.q4cdn.com",  # Alphabet investor-relations CDN, linked from abc.xyz
    }
)

_DOCUMENT_ID_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
_FILENAME_RE = re.compile(r"^[a-z0-9]+(?:[-.][a-z0-9]+)*\.pdf$")
_SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
_ISO_DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
_SEMVER_RE = re.compile(r"^\d+\.\d+\.\d+$")

_TOP_LEVEL_KEYS = frozenset(
    {"schema_version", "corpus_id", "corpus_version", "description", "documents"}
)
_DOCUMENT_KEYS = frozenset(
    {
        "document_id",
        "company",
        "ticker",
        "title",
        "document_type",
        "fiscal_period",
        "period_end",
        "publication_date",
        "source_url",
        "download_url",
        "acquisition_date",
        "filename",
        "sha256",
        "size_bytes",
        "page_count",
    }
)
_OPTIONAL_DOCUMENT_KEYS = frozenset({"download_url"})


class ManifestError(ValueError):
    """Raised when the manifest is malformed. ``problems`` lists every issue found."""

    def __init__(self, problems: list[str]) -> None:
        self.problems = problems
        super().__init__("; ".join(problems))


@dataclass(frozen=True, slots=True)
class DocumentEntry:
    document_id: str
    company: str
    ticker: str
    title: str
    document_type: str
    fiscal_period: str
    period_end: date
    publication_date: date
    source_url: str
    download_url: str | None
    acquisition_date: date
    filename: str
    sha256: str
    size_bytes: int
    page_count: int


@dataclass(frozen=True, slots=True)
class CorpusManifest:
    corpus_id: str
    corpus_version: str
    description: str
    documents: tuple[DocumentEntry, ...]

    def get(self, document_id: str) -> DocumentEntry | None:
        return next((d for d in self.documents if d.document_id == document_id), None)

    @property
    def page_counts(self) -> dict[str, int]:
        return {d.document_id: d.page_count for d in self.documents}


def is_safe_filename(name: str) -> bool:
    """True for a bare, lowercase ``*.pdf`` name with no separators or traversal."""
    return bool(_FILENAME_RE.fullmatch(name)) and ".." not in name


def check_https_url(url: str, *, allowed_hosts: frozenset[str] | None = None) -> str | None:
    """Return a problem description, or None if ``url`` is an acceptable HTTPS URL."""
    parts = urlsplit(url)
    if parts.scheme != "https":
        return f"URL must use https: {url!r}"
    if not parts.hostname:
        return f"URL has no host: {url!r}"
    if parts.username or parts.password:
        return f"URL must not embed credentials: {url!r}"
    if allowed_hosts is not None and parts.hostname not in allowed_hosts:
        return f"URL host {parts.hostname!r} is not an approved download host"
    return None


class _Reader:
    """Collects typed field reads and their problems for one JSON object."""

    def __init__(self, obj: dict[str, Any], where: str, problems: list[str]) -> None:
        self.obj = obj
        self.where = where
        self.problems = problems

    def text(self, key: str, *, optional: bool = False) -> str:
        value = self.obj.get(key)
        if value is None and optional:
            return ""
        if not isinstance(value, str) or not value.strip():
            self.problems.append(f"{self.where}: '{key}' must be a non-empty string")
            return ""
        return value

    def iso_date(self, key: str) -> date:
        raw = self.text(key)
        if raw and _ISO_DATE_RE.fullmatch(raw):
            try:
                return date.fromisoformat(raw)
            except ValueError:
                pass
        if raw:
            self.problems.append(f"{self.where}: '{key}' must be an ISO 8601 date (YYYY-MM-DD)")
        return date.min

    def positive_int(self, key: str) -> int:
        value = self.obj.get(key)
        if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
            self.problems.append(f"{self.where}: '{key}' must be a positive integer")
            return 0
        return value


def _check_keys(
    obj: dict[str, Any],
    allowed: frozenset[str],
    optional: frozenset[str],
    where: str,
    problems: list[str],
) -> None:
    unknown = sorted(set(obj) - allowed)
    missing = sorted(allowed - optional - set(obj))
    if unknown:
        problems.append(f"{where}: unknown field(s) {unknown}")
    if missing:
        problems.append(f"{where}: missing field(s) {missing}")


def _parse_document(obj: object, index: int, problems: list[str]) -> DocumentEntry | None:
    where = f"documents[{index}]"
    if not isinstance(obj, dict):
        problems.append(f"{where}: must be an object")
        return None
    _check_keys(obj, _DOCUMENT_KEYS, _OPTIONAL_DOCUMENT_KEYS, where, problems)
    r = _Reader(obj, where, problems)

    document_id = r.text("document_id")
    if document_id:
        r.where = where = f"document '{document_id}'"
        if not _DOCUMENT_ID_RE.fullmatch(document_id):
            problems.append(f"{where}: 'document_id' must be lowercase kebab-case")

    source_url = r.text("source_url")
    if source_url and (issue := check_https_url(source_url)):
        problems.append(f"{where}: source_url: {issue}")

    download_url: str | None = None
    if "download_url" in obj and obj["download_url"] is not None:
        download_url = r.text("download_url")
        if download_url and (
            issue := check_https_url(download_url, allowed_hosts=ALLOWED_DOWNLOAD_HOSTS)
        ):
            problems.append(f"{where}: download_url: {issue}")

    filename = r.text("filename")
    if filename and not is_safe_filename(filename):
        problems.append(
            f"{where}: unsafe filename {filename!r} (expected a bare lowercase *.pdf name)"
        )

    sha256 = r.text("sha256")
    if sha256 and not _SHA256_RE.fullmatch(sha256):
        problems.append(f"{where}: 'sha256' must be 64 lowercase hex characters")

    period_end = r.iso_date("period_end")
    publication_date = r.iso_date("publication_date")
    acquisition_date = r.iso_date("acquisition_date")
    if date.min not in (period_end, publication_date) and publication_date < period_end:
        problems.append(f"{where}: publication_date precedes period_end")
    if date.min not in (publication_date, acquisition_date) and acquisition_date < publication_date:
        problems.append(f"{where}: acquisition_date precedes publication_date")

    return DocumentEntry(
        document_id=document_id,
        company=r.text("company"),
        ticker=r.text("ticker"),
        title=r.text("title"),
        document_type=r.text("document_type"),
        fiscal_period=r.text("fiscal_period"),
        period_end=period_end,
        publication_date=publication_date,
        source_url=source_url,
        download_url=download_url,
        acquisition_date=acquisition_date,
        filename=filename,
        sha256=sha256,
        size_bytes=r.positive_int("size_bytes"),
        page_count=r.positive_int("page_count"),
    )


def parse_manifest(data: object) -> CorpusManifest:
    """Validate the decoded JSON structure and return a typed manifest.

    Raises :class:`ManifestError` listing every structural problem found.
    """
    problems: list[str] = []
    if not isinstance(data, dict):
        raise ManifestError(["manifest root must be a JSON object"])
    _check_keys(data, _TOP_LEVEL_KEYS, frozenset(), "manifest", problems)

    schema_version = data.get("schema_version")
    if schema_version != MANIFEST_SCHEMA_VERSION or isinstance(schema_version, bool):
        problems.append(f"manifest: 'schema_version' must be {MANIFEST_SCHEMA_VERSION}")

    r = _Reader(data, "manifest", problems)
    corpus_id = r.text("corpus_id")
    if corpus_id and corpus_id != EXPECTED_CORPUS_ID:
        problems.append(f"manifest: 'corpus_id' must be {EXPECTED_CORPUS_ID!r}")
    corpus_version = r.text("corpus_version")
    if corpus_version and not _SEMVER_RE.fullmatch(corpus_version):
        problems.append("manifest: 'corpus_version' must be MAJOR.MINOR.PATCH")
    description = r.text("description")

    raw_documents = data.get("documents")
    documents: list[DocumentEntry] = []
    if not isinstance(raw_documents, list):
        problems.append("manifest: 'documents' must be a list")
    else:
        for index, item in enumerate(raw_documents):
            entry = _parse_document(item, index, problems)
            if entry is not None:
                documents.append(entry)

    ids = [d.document_id for d in documents if d.document_id]
    filenames = [d.filename for d in documents if d.filename]
    for label, values in (("document_id", ids), ("filename", filenames)):
        duplicates = sorted({v for v in values if values.count(v) > 1})
        if duplicates:
            problems.append(f"manifest: duplicate {label}(s) {duplicates}")
    if ids != sorted(ids):
        problems.append("manifest: documents must be sorted by document_id")

    if problems:
        raise ManifestError(problems)
    return CorpusManifest(
        corpus_id=corpus_id,
        corpus_version=corpus_version,
        description=description,
        documents=tuple(documents),
    )


def load_manifest(path: Path) -> CorpusManifest:
    """Read and parse a manifest file. Raises :class:`ManifestError` on any problem."""
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise ManifestError([f"cannot read manifest {path}: {exc}"]) from exc
    try:
        data: object = json.loads(text)
    except json.JSONDecodeError as exc:
        raise ManifestError([f"manifest is not valid JSON: {exc}"]) from exc
    return parse_manifest(data)
