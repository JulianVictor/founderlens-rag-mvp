"""Structured grounded answer schema and response invariants (Commit 5.3).

**Provider-facing schema.** :class:`GroundedAnswer` is a strict Pydantic model
(``extra="forbid"``, every field required, no defaults, frozen). The provider
sends it unchanged through the existing ``strict_output_format`` as the native
Structured Outputs ``json_schema``. The class and field descriptions in it are
written for the model: they explain the answer statuses, claim types and what
``limitations`` may contain. They do not change the committed grounded prompt
``grounded-financial-v1``. The schema contains only answer content. Document
IDs, pages, URLs, offsets, scores, hashes and configuration identities are
trusted application metadata and are never generated by the model.

**Application invariants** (:func:`answer_problems`, version
:data:`RESPONSE_INVARIANT_VERSION`) are checked locally after parsing, because
strict mode cannot express them:

- ``answered``: at least one claim and no limitations;
- ``partially_answered``: at least one claim and at least one limitation;
- ``insufficient_evidence``: no claims and at least one limitation;
- every claim has non-blank text and cites one or more evidence IDs;
- every ID matches ``E`` plus two digits and exists in this request's evidence
  registry. Excluded candidates never get an ID, so citing one fails. IDs are
  request-scoped labels: an ID that also exists in this registry (``E01`` from
  another request, say) is indistinguishable from this run's own, so this check
  cannot detect where an ID came from. It only guarantees that every cited ID
  resolves to this run's evidence;
- a claim citing the same ID twice is **rejected**, not deduplicated;
- every limitation is non-blank.

A violation raises :class:`ResponseContractError`. Nothing is dropped or
repaired, and no second request is made.

Passing these checks makes an answer *structurally* valid. It does not show
that the cited evidence supports the claim, that a calculation is right, or
that ``limitations`` contains no uncited financial facts. The field
description asks for that last point, but schema validation cannot enforce
it. Those are later citation-validation and evaluation concerns.
"""

from __future__ import annotations

import hashlib
import json
import re
from collections.abc import Sequence
from dataclasses import dataclass
from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from founderlens.generation.context import EvidenceRegistry
from founderlens.generation.errors import GenerationError, safe_token
from founderlens.generation.openai_provider import strict_output_format
from founderlens.generation.token_budget import TokenCounter

ANSWER_SCHEMA_VERSION = 1
RESPONSE_INVARIANT_VERSION = 1
EVIDENCE_ID_SYNTAX = r"E[0-9]{2}"
DUPLICATE_REFERENCE_POLICY = "reject"
_EVIDENCE_ID = re.compile(EVIDENCE_ID_SYNTAX)


class ResponseContractError(GenerationError):
    """A parsed answer breaks the response invariants. Messages never quote answer text."""

    category = "response_contract"

    def __init__(self, problems: Sequence[str], *, request_id: str | None = None) -> None:
        self.problems = tuple(problems)
        super().__init__("; ".join(self.problems[:5]), request_id=request_id)


class AnswerStatus(StrEnum):
    """answered: the evidence fully answers the question; limitations is empty.
    partially_answered: the evidence answers part of the question; list what is missing in
    limitations. insufficient_evidence: the evidence cannot answer the question; claims is
    empty and limitations explains why."""

    ANSWERED = "answered"
    PARTIALLY_ANSWERED = "partially_answered"
    INSUFFICIENT_EVIDENCE = "insufficient_evidence"


class ClaimType(StrEnum):
    """reported: stated directly in the evidence, including clearly labelled guidance or
    forecasts. calculated: a figure derived from cited evidence values. synthesis: a
    supported non-numerical interpretation or comparison."""

    REPORTED = "reported"
    CALCULATED = "calculated"
    SYNTHESIS = "synthesis"


class Claim(BaseModel):
    """One factual statement supported by the cited evidence records."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    text: str = Field(
        description=(
            "The statement, keeping the company, reporting period, currency and units "
            "exactly as the evidence gives them."
        )
    )
    # No field description: a $ref with sibling keys is not accepted in strict mode, so the
    # claim-type semantics live in the ClaimType description.
    claim_type: ClaimType
    evidence_ids: tuple[str, ...] = Field(
        description=(
            "IDs of the supplied evidence records that support this statement, for example "
            '"E01". At least one, each listed once, and only IDs present in the input.'
        )
    )


class GroundedAnswer(BaseModel):
    """An answer to the financial research question built only from the supplied evidence."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    status: AnswerStatus  # semantics in the AnswerStatus description (see ClaimType note)
    claims: tuple[Claim, ...] = Field(
        description=(
            "Factual statements that answer the question, each citing its evidence. "
            "Empty only when status is insufficient_evidence."
        )
    )
    limitations: tuple[str, ...] = Field(
        description=(
            "Parts of the question the supplied evidence cannot establish. Describe what is "
            "missing; do not state financial facts or figures here, because limitations are "
            "not cited. Empty when status is answered."
        )
    )

    @property
    def abstained(self) -> bool:
        """The deterministic abstention flag (protocol section 6.6)."""
        return self.status is AnswerStatus.INSUFFICIENT_EVIDENCE


# --------------------------------------------------------------------------- #
# Invariants
# --------------------------------------------------------------------------- #


def answer_problems(answer: GroundedAnswer, evidence: EvidenceRegistry) -> list[str]:
    """Every response-invariant violation; empty when the answer is structurally valid."""
    problems: list[str] = []
    status = answer.status
    if status is AnswerStatus.INSUFFICIENT_EVIDENCE:
        if answer.claims:
            problems.append("insufficient_evidence must have no claims")
    elif not answer.claims:
        problems.append(f"{status.value} needs at least one claim")
    if status is AnswerStatus.ANSWERED and answer.limitations:
        problems.append("answered must have no limitations")
    if status is not AnswerStatus.ANSWERED and not answer.limitations:
        problems.append(f"{status.value} needs at least one limitation")
    for position, limitation in enumerate(answer.limitations, start=1):
        if not limitation.strip():
            problems.append(f"limitation {position} is blank")
    for position, claim in enumerate(answer.claims, start=1):
        label = f"claim {position}"
        if not claim.text.strip():
            problems.append(f"{label}: text is blank")
        if not claim.evidence_ids:
            problems.append(f"{label}: cites no evidence")
        seen: set[str] = set()
        for evidence_id in claim.evidence_ids:
            shown = safe_token(evidence_id)
            if evidence_id in seen:
                problems.append(f"{label}: evidence ID {shown} is cited twice")
                continue
            seen.add(evidence_id)
            if not _EVIDENCE_ID.fullmatch(evidence_id):
                problems.append(f"{label}: {shown} is not an evidence ID (E plus two digits)")
            elif evidence_id not in evidence:
                problems.append(f"{label}: evidence ID {shown} is not in this request's evidence")
    return problems


def validate_answer(
    answer: GroundedAnswer, evidence: EvidenceRegistry, *, request_id: str | None = None
) -> None:
    """Raise :class:`ResponseContractError` listing every violation."""
    problems = answer_problems(answer, evidence)
    if problems:
        raise ResponseContractError(problems, request_id=request_id)


