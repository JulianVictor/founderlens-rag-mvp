def answer_text_format() -> dict[str, Any]:
    """The exact ``text.format`` object the provider sends for :class:`GroundedAnswer`."""
    return dict(strict_output_format(GroundedAnswer))


def answer_schema_definition() -> dict[str, Any]:
    """Everything that defines the response contract (no request content)."""
    return {
        "answer_schema_version": ANSWER_SCHEMA_VERSION,
        "response_invariant_version": RESPONSE_INVARIANT_VERSION,
        "evidence_id_syntax": EVIDENCE_ID_SYNTAX,
        "duplicate_reference_policy": DUPLICATE_REFERENCE_POLICY,
        "text_format": answer_text_format(),
    }


def answer_schema_sha256() -> str:
    canonical = json.dumps(
        answer_schema_definition(), sort_keys=True, separators=(",", ":"), ensure_ascii=False
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def answer_schema_id() -> str:
    """First 12 hex characters of :func:`answer_schema_sha256`."""
    return answer_schema_sha256()[:12]


def _compact(value: object) -> str:
    return json.dumps(value, separators=(",", ":"), ensure_ascii=False)


@dataclass(frozen=True, slots=True)
class SchemaTokenReport:
    """Local token counts of the structured-output request parameter (estimates)."""

    tokenizer: str
    schema_tokens: int
    wrapper_tokens: int
    text_parameter_tokens: int
    framing_allowance_tokens: int

    @property
    def remaining_allowance_tokens(self) -> int:
        return self.framing_allowance_tokens - self.text_parameter_tokens

    def to_dict(self) -> dict[str, Any]:
        return {
            "estimate": "local count of the serialized text parameter, not provider usage",
            "tokenizer": self.tokenizer,
            "schema_json_tokens": self.schema_tokens,
            "wrapper_tokens": self.wrapper_tokens,
            "text_parameter_tokens": self.text_parameter_tokens,
            "framing_allowance_tokens": self.framing_allowance_tokens,
            "remaining_allowance_tokens": self.remaining_allowance_tokens,
        }


def schema_token_report(counter: TokenCounter, framing_allowance: int) -> SchemaTokenReport:
    """Counts for the schema JSON, the wrapper around it and the whole ``text`` parameter.

    Counted separately, so they are not additive. ``text_parameter_tokens`` is the
    combined local estimate compared with the allowance. The provider's own
    framing of the schema is not visible locally.
    """
    text_format = answer_text_format()
    return SchemaTokenReport(
        tokenizer=counter.identity,
        schema_tokens=counter.count(_compact(text_format["schema"])),
        wrapper_tokens=counter.count(_compact({"format": {**text_format, "schema": {}}})),
        text_parameter_tokens=counter.count(_compact({"format": text_format})),
        framing_allowance_tokens=framing_allowance,
    )
