"""End-to-end demonstration: question to cited response (Commit 5.4).

Usage::

    python -m founderlens.generation.demo                    # offline, SYNTHETIC answers
    python -m founderlens.generation.demo --show-passages    # also print cited passages
    python -m founderlens.generation.demo --live --question "..."   # PAID, one request

The offline demo runs the real path (V2 retrieval, the context builder, the
structured-generation service, citation resolution and rendering) with a
**synthetic scripted provider**. Its "answers" are placeholders that cite real
evidence IDs from the request, so they show the mechanics, not model output,
and every one is labelled SYNTHETIC. No network or key is needed.

``--live`` is the explicit opt-in for a paid request. It needs
``OPENAI_API_KEY``, sends the question, the grounded instructions and up to ten
public-source evidence chunks to OpenAI (``store=False``), and makes at most
one request with SDK retries disabled. The semantic configuration
(``cbc4e415c848``) is unchanged. Without ``--live`` nothing is sent.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from collections.abc import Sequence
from typing import Any

from founderlens.config import ConfigError, Settings, load_settings
from founderlens.corpus.manifest import ManifestError, load_manifest
from founderlens.generation.answer import AnswerStatus
from founderlens.generation.citations import CitationResolver, GroundedResponse
from founderlens.generation.config import DEFAULT_GENERATION_CONFIG, GenerationConfig
from founderlens.generation.errors import GenerationError
from founderlens.generation.schema import (
    GenerationRequest,
    GenerationResult,
    LLMProvider,
    ProviderIdentity,
    SchemaT,
    TokenUsage,
)
from founderlens.generation.service import GroundedGenerationService
from founderlens.generation.token_budget import TokenCounter, load_generation_tokenizer
from founderlens.retrieval.policy import PolicyRetriever, load_policy_retriever
from founderlens.retrieval.schema import RetrievalError

SYNTHETIC_PROVIDER = "synthetic-demo"
SYNTHETIC_MODEL = "synthetic-demo (no model call)"
# Questions written for this demo without consulting the evaluation files.
DEMO_SCENARIOS: tuple[tuple[AnswerStatus | None, str], ...] = (
    (
        AnswerStatus.ANSWERED,
        "What revenue did NVIDIA report for its Data Center business in the fourth quarter "
        "of fiscal 2025?",
    ),
    (AnswerStatus.PARTIALLY_ANSWERED, "How did Google Cloud revenue and operating income change?"),
    (
        AnswerStatus.INSUFFICIENT_EVIDENCE,
        "What was NVIDIA's revenue from customers in Antarctica in fiscal 2025?",
    ),
    (None, "zyzzyva quokka"),  # empty retrieval: local abstention, no provider call
)


class SyntheticDemoProvider:
    """Scripted placeholder answers citing the request's own evidence IDs. Not a model."""

    def __init__(
        self, status: AnswerStatus, config: GenerationConfig = DEFAULT_GENERATION_CONFIG
    ) -> None:
        self._status = status
        self._identity = ProviderIdentity(
            SYNTHETIC_PROVIDER, "none", config.model, config.config_id
        )

    @property
    def identity(self) -> ProviderIdentity:
        return self._identity

    def generate_text(self, request: GenerationRequest) -> GenerationResult[None]:
        raise GenerationError("the synthetic demo provider only supports structured answers")

    def generate_structured(
        self, request: GenerationRequest, schema: type[SchemaT]
    ) -> GenerationResult[SchemaT]:
        ids = [e["evidence_id"] for e in json.loads(request.input_text)["evidence"]]
        payload = json.dumps(self._answer(ids))
        return GenerationResult(
            text=payload,
            parsed=schema.model_validate_json(payload),
            status="completed",
            requested_model=self._identity.model,
            response_model=SYNTHETIC_MODEL,
            response_id="synthetic-demo",
            request_id=None,
            usage=TokenUsage(),  # no provider usage exists, so none is reported
            latency_ms=0.0,
            provider=self._identity,
        )

    def close(self) -> None:
        return None

    def _answer(self, ids: list[str]) -> dict[str, Any]:
        limitation = "SYNTHETIC placeholder limitation (scripted, not generated by a model)."
        if self._status is AnswerStatus.INSUFFICIENT_EVIDENCE:
            return {"status": self._status.value, "claims": [], "limitations": [limitation]}
        second = ids[1] if len(ids) > 1 else ids[0]
        claims = [
            {
                "text": f"SYNTHETIC placeholder claim citing {ids[0]} and {second}.",
                "claim_type": "reported",
                "evidence_ids": list(dict.fromkeys([ids[0], second])),
            },
            {
                "text": f"SYNTHETIC placeholder claim citing {ids[0]} again.",
                "claim_type": "synthesis",
                "evidence_ids": [ids[0]],
            },
        ]
        if self._status is AnswerStatus.ANSWERED:
            return {"status": self._status.value, "claims": claims, "limitations": []}
        return {"status": self._status.value, "claims": claims[:1], "limitations": [limitation]}


class SingleRequestProvider:
    """Allows exactly one provider request; a second is refused before sending."""

    def __init__(self, inner: LLMProvider) -> None:
        self._inner = inner
        self.requests = 0

    @property
    def identity(self) -> ProviderIdentity:
        return self._inner.identity

    def generate_text(self, request: GenerationRequest) -> GenerationResult[None]:
        raise GenerationError("the demo uses structured generation only")

    def generate_structured(
        self, request: GenerationRequest, schema: type[SchemaT]
    ) -> GenerationResult[SchemaT]:
        if self.requests >= 1:
            raise GenerationError("the live demo allows a single request")
        self.requests += 1
        return self._inner.generate_structured(request, schema)

    def close(self) -> None:
        self._inner.close()


def _load(settings: Settings) -> tuple[PolicyRetriever, TokenCounter, CitationResolver]:
    retriever = load_policy_retriever(settings)
    counter = load_generation_tokenizer(settings)
    resolver = CitationResolver(retriever.collection, load_manifest(settings.corpus_manifest_path))
    return retriever, counter, resolver


def run_offline_demo(settings: Settings) -> list[tuple[str, GroundedResponse]]:
    """Every scenario through the full path with synthetic answers; returns the responses."""
    retriever, counter, resolver = _load(settings)
    responses = []
    for status, question in DEMO_SCENARIOS:
        provider = SyntheticDemoProvider(status or AnswerStatus.INSUFFICIENT_EVIDENCE)
        service = GroundedGenerationService(retriever, counter, provider)
        label = status.value if status is not None else "local_empty_retrieval"
        responses.append((label, resolver.resolve(service.answer(question))))
    return responses


def run_live_demo(
    settings: Settings, question: str, provider: LLMProvider
) -> tuple[GroundedResponse, int]:
    """One live question through the full path; at most one provider request."""
    retriever, counter, resolver = _load(settings)
    single = SingleRequestProvider(provider)
    config = GenerationConfig(max_retries=0)  # retries are operational: config_id unchanged
    service = GroundedGenerationService(retriever, counter, single, generation_config=config)
    return resolver.resolve(service.answer(question)), single.requests


def _print_response(
    label: str, response: GroundedResponse, *, show_passages: bool, synthetic: bool
) -> None:
    note = "SYNTHETIC scripted answer, no model call" if synthetic else "live model answer"
    if response.run.provider_result is None:
        note = "local abstention, no provider call"
    print(f"=== {label} ({note}) ===")
    print(f"question: {json.dumps(response.run.prepared.question, ensure_ascii=False)}")
    print(response.render().text, end="")
    meta = response.metadata()
    print(
        f"origin {meta['origin']}; abstained {meta['abstained']}; uncited model-visible "
        f"evidence {meta['uncited_evidence_ids']}; usage {meta['usage']}"
    )
    if show_passages:
        for citation in response.citations:
            print(
                f"--- [{citation.number}] {citation.chunk_id} chars "
                f"{citation.start_char}-{citation.end_char} (normalized page text)"
            )
            print(json.dumps(citation.text, ensure_ascii=False))
    print()


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m founderlens.generation.demo",
        description="Question to cited response. Offline with synthetic answers by default.",
    )
    parser.add_argument("--show-passages", action="store_true", help="Print cited passages.")
    parser.add_argument(
        "--live", action="store_true", help="PAID: send one request to OpenAI (opt-in)."
    )
    parser.add_argument("--question", default=None, help="Question for --live.")
    parser.add_argument("--project-root", default=None, help="Absolute project root override.")
    args = parser.parse_args(argv)
    if args.question is not None and not args.live:
        parser.error("--question is only used with --live")
    if args.live and not args.question:
        parser.error("--live needs --question")
    try:
        settings = load_settings(args.project_root)
        if not args.live:
            for label, response in run_offline_demo(settings):
                _print_response(label, response, show_passages=args.show_passages, synthetic=True)
            return 0
        if not os.environ.get("OPENAI_API_KEY", "").strip():
            print("error: --live needs OPENAI_API_KEY; nothing was sent", file=sys.stderr)
            return 1
        from founderlens.generation.openai_provider import OpenAIProvider

        print("PAID: sending one request to OpenAI (retries disabled, store=False).")
        with OpenAIProvider(GenerationConfig(max_retries=0)) as provider:
            response, requests = run_live_demo(settings, args.question, provider)
        _print_response("live", response, show_passages=args.show_passages, synthetic=False)
        print(f"provider requests made: {requests}")
        return 0
    except ConfigError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    except (GenerationError, RetrievalError, ManifestError) as exc:
        print(f"Demo FAILED: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
