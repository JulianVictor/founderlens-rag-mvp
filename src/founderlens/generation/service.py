"""Grounded generation service (Commit 5.3).

:class:`GroundedGenerationService` composes the existing pieces. It receives
initialized dependencies: one loaded :class:`PolicyRetriever` (BM25 V2, top
10), one :class:`TokenCounter` and one :class:`LLMProvider`. For each
question it:

1. calls ``prepare_generation_input``. That validates the question, retrieves,
   validates candidates and builds the request and the evidence registry;
2. for ``empty_retrieval`` or ``no_evidence_fits``, returns a **local**
   ``insufficient_evidence`` answer without calling the provider. The reason
   is recorded, and the answer says that no matching evidence was retrieved
   or that it did not fit the context budget, never that the documents lack
   the facts;
3. for ``evidence_selected``, makes exactly one
   ``provider.generate_structured(prepared.request, GroundedAnswer)`` call;
4. checks the response invariants against the *same* prepared evidence
   registry (:func:`~founderlens.generation.answer.validate_answer`).

Errors are never turned into answers. Invalid questions, incompatible
artifacts, malformed candidates, every provider error (authentication,
permission, rate limit, quota, timeout, connection, refusal, incomplete
output, model mismatch, invalid structured output) and response-contract
violations propagate as their own exceptions. There is no orchestration-level
retry, no model fallback and no repair request.

A result is a structured generation with basic reference checks: it is not
citation-resolved (Commit 5.4) and not verified for factual support.
"""

from __future__ import annotations

import logging
import time
from collections.abc import Mapping
from dataclasses import dataclass
from enum import StrEnum
from typing import Any

from founderlens.generation.answer import (
    ANSWER_SCHEMA_VERSION,
    RESPONSE_INVARIANT_VERSION,
    AnswerStatus,
    GroundedAnswer,
    answer_schema_id,
    schema_token_report,
    validate_answer,
)
from founderlens.generation.config import DEFAULT_GENERATION_CONFIG, GenerationConfig
from founderlens.generation.context import (
    DEFAULT_CONTEXT_CONFIG,
    ContextCompatibilityError,
    ContextConfig,
    ContextStatus,
    PreparedGenerationInput,
    prepare_generation_input,
)
from founderlens.generation.errors import GenerationError
from founderlens.generation.schema import GenerationResult, LLMProvider
from founderlens.generation.token_budget import TokenCounter
from founderlens.retrieval.policy import PolicyRetriever

logger = logging.getLogger(__name__)


class AnswerOrigin(StrEnum):
    MODEL = "model"  # generated by the provider from selected evidence
    LOCAL = "local"  # local abstention; the provider was not called


class LocalAbstentionReason(StrEnum):
    EMPTY_RETRIEVAL = "empty_retrieval"
    NO_EVIDENCE_FITS = "no_evidence_fits"


LOCAL_LIMITATIONS: Mapping[LocalAbstentionReason, str] = {
    LocalAbstentionReason.EMPTY_RETRIEVAL: (
        "The lexical retriever found no evidence matching the question's words, so no evidence "
        "was available to answer it. This does not show that the source documents lack the "
        "requested information."
    ),
    LocalAbstentionReason.NO_EVIDENCE_FITS: (
        "Evidence was retrieved, but even the highest-ranked passage did not fit the context "
        "budget, so no evidence was supplied. This does not show that the source documents "
        "lack the requested information."
    ),
}


@dataclass(frozen=True, slots=True)
class GenerationRunResult:
    """One question's outcome, tied to the exact evidence the model saw."""

    answer: GroundedAnswer
    origin: AnswerOrigin
    local_abstention_reason: LocalAbstentionReason | None
    prepared: PreparedGenerationInput
    provider_result: GenerationResult[GroundedAnswer] | None
    answer_schema_id: str
    context_ms: float
    provider_ms: float | None
    total_ms: float

    @property
    def provider_called(self) -> bool:
        return self.provider_result is not None

    @property
    def abstained(self) -> bool:
        return self.answer.abstained

    def identities(self) -> dict[str, Any]:
        ids = self.prepared.identities()
        ids["answer_schema_id"] = self.answer_schema_id
        ids["answer_schema_version"] = ANSWER_SCHEMA_VERSION
        ids["response_invariant_version"] = RESPONSE_INVARIANT_VERSION
        return ids

    def metadata(self) -> dict[str, Any]:
        """Diagnostics without question, evidence or answer text.

        ``context`` is deterministic for identical inputs and artifacts. ``generation``
        summarizes the (non-deterministic) model output, and ``runtime`` holds
        measurements and provider-reported values.
        """
        context = self.prepared.metadata()
        context["identities"] = self.identities()
        provider = self.provider_result
        return {
            "context": context,
            "generation": {
                "origin": self.origin.value,
                "provider_called": provider is not None,
                "preparation_status": self.prepared.status.value,
                "local_abstention_reason": None
                if self.local_abstention_reason is None
                else self.local_abstention_reason.value,
                "answer_status": self.answer.status.value,
                "abstained": self.abstained,
                "claim_count": len(self.answer.claims),
                "claim_types": [c.claim_type.value for c in self.answer.claims],
                "cited_evidence_ids": sorted(
                    {i for c in self.answer.claims for i in c.evidence_ids}
                ),
                "limitation_count": len(self.answer.limitations),
            },
            "runtime": {
                "provider": None if provider is None else provider.metadata(),
                "context_ms": round(self.context_ms, 3),
                "provider_ms": None if self.provider_ms is None else round(self.provider_ms, 3),
                "total_ms": round(self.total_ms, 3),
            },
        }


class GroundedGenerationService:
    """Retrieval, context and one structured provider call per question."""

    def __init__(
        self,
        retriever: PolicyRetriever,
        counter: TokenCounter,
        provider: LLMProvider,
        *,
        context_config: ContextConfig = DEFAULT_CONTEXT_CONFIG,
        generation_config: GenerationConfig = DEFAULT_GENERATION_CONFIG,
    ) -> None:
        if provider.identity.config_id != generation_config.config_id:
            raise ContextCompatibilityError(
                f"provider configuration {provider.identity.config_id} differs from the "
                f"generation configuration {generation_config.config_id}"
            )
        schema_tokens = schema_token_report(counter, context_config.framing_allowance_tokens)
        if schema_tokens.remaining_allowance_tokens < 0:
            raise ContextCompatibilityError(
                f"the answer schema needs {schema_tokens.text_parameter_tokens} local tokens, "
                f"more than the {context_config.framing_allowance_tokens}-token framing allowance"
            )
        self._retriever = retriever
        self._counter = counter
        self._provider = provider
        self._context_config = context_config
        self._generation_config = generation_config
        self._schema_id = answer_schema_id()
        self._schema_tokens = schema_tokens

    @property
    def answer_schema_id(self) -> str:
        return self._schema_id

    def schema_token_report(self) -> dict[str, Any]:
        return self._schema_tokens.to_dict()

    def answer(self, question: str) -> GenerationRunResult:
        """Answer one question; see the module docstring for the flow and error contract."""
        started = time.perf_counter()
        try:
            prepared = prepare_generation_input(
                question,
                self._retriever,
                self._counter,
                config=self._context_config,
                generation_config=self._generation_config,
            )
            context_ms = (time.perf_counter() - started) * 1000
            if prepared.status is not ContextStatus.EVIDENCE_SELECTED:
                result = self._local_abstention(prepared, started, context_ms)
            else:
                result = self._generate(prepared, started, context_ms)
        except GenerationError as error:
            logger.warning(
                "grounded generation failed category=%s answer_schema_id=%s request_id=%s",
                error.category,
                self._schema_id,
                error.request_id,
            )
            raise
        generation = result.metadata()["generation"]
        logger.info(
            "grounded generation origin=%s preparation_status=%s answer_status=%s claims=%s "
            "selected_evidence=%s answer_schema_id=%s total_ms=%.1f",
            generation["origin"],
            generation["preparation_status"],
            generation["answer_status"],
            generation["claim_count"],
            len(prepared.evidence),
            self._schema_id,
            result.total_ms,
        )
        return result

    def _local_abstention(
        self, prepared: PreparedGenerationInput, started: float, context_ms: float
    ) -> GenerationRunResult:
        reason = (
            LocalAbstentionReason.EMPTY_RETRIEVAL
            if prepared.status is ContextStatus.EMPTY_RETRIEVAL
            else LocalAbstentionReason.NO_EVIDENCE_FITS
        )
        answer = GroundedAnswer(
            status=AnswerStatus.INSUFFICIENT_EVIDENCE,
            claims=(),
            limitations=(LOCAL_LIMITATIONS[reason],),
        )
        validate_answer(answer, prepared.evidence)
        return GenerationRunResult(
            answer=answer,
            origin=AnswerOrigin.LOCAL,
            local_abstention_reason=reason,
            prepared=prepared,
            provider_result=None,
            answer_schema_id=self._schema_id,
            context_ms=context_ms,
            provider_ms=None,
            total_ms=(time.perf_counter() - started) * 1000,
        )

    def _generate(
        self, prepared: PreparedGenerationInput, started: float, context_ms: float
    ) -> GenerationRunResult:
        provider_started = time.perf_counter()
        generated = self._provider.generate_structured(prepared.request, GroundedAnswer)
        provider_ms = (time.perf_counter() - provider_started) * 1000
        validate_answer(
            generated.parsed,
            prepared.evidence,
            request_id=generated.request_id,
            usage=generated.usage,  # diagnostics only: a rejected response still cost tokens
        )
        return GenerationRunResult(
            answer=generated.parsed,
            origin=AnswerOrigin.MODEL,
            local_abstention_reason=None,
            prepared=prepared,
            provider_result=generated,
            answer_schema_id=self._schema_id,
            context_ms=context_ms,
            provider_ms=provider_ms,
            total_ms=(time.perf_counter() - started) * 1000,
        )
